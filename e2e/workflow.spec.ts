import { expect, test, type Page } from '@playwright/test';
import type { Card, ReviewResult, StudyBatch } from '../shared/types';
import { USER_A, USER_B, WORD_DRAFT } from '../test/fixtures';
import { allCards } from './cards';

async function signIn(page: Page, user: typeof USER_A) {
	await page.setExtraHTTPHeaders({ 'CF-Connecting-IP': `workflow-${crypto.randomUUID()}` });
	await page.goto('/');
	await page.getByLabel('Nazwa użytkownika').fill(user.username);
	await page.getByLabel('Hasło', { exact: true }).fill(user.password);
	await page.getByRole('button', { name: 'Zaloguj', exact: true }).click();
	await expect(page.getByText(user.displayName, { exact: true })).toBeVisible();
}

test('shares the server key for generation and grading while keeping learner progress and retries separate', async ({ page, browser, baseURL }) => {
	const context = await browser.newContext({ baseURL });
	const other = await context.newPage();
	const headers = { Origin: baseURL! };
	let card: Card | undefined;
	try {
		await signIn(page, USER_A);
		await signIn(other, USER_B);
		await other.getByRole('button', { name: 'Dodaj', exact: true }).click();
		await other.getByLabel('Słowo lub wyrażenie').fill('słowo');
		await other.getByRole('button', { name: 'Przygotuj fiszkę', exact: true }).click();
		await expect(other.getByLabel('Przykład po polsku')).toHaveValue(WORD_DRAFT.examplePl);
		const saved = other.waitForResponse(response => response.url().endsWith('/api/cards') && response.request().method() === 'POST');
		await other.getByRole('button', { name: 'Zapisz', exact: true }).click();
		expect((await saved).status()).toBe(201);
		card = await (await saved).json();
		expect(card?.createdBy).toBe(USER_B.id);
		const cardId = card!.id;
		await expect(other.getByRole('status')).toContainText('Fiszka zapisana.');
		await page.getByRole('button', { name: 'Słówka', exact: true }).click();
		await expect(page.getByRole('button', { name: 'Słowo / Слово', exact: true })).toBeVisible();
		await other.getByRole('button', { name: 'Nauka', exact: true }).click();
		await other.getByRole('button', { name: 'PL -> RU', exact: true }).click();
		await other.getByLabel('Odpowiedź po rosyjsku').fill('термин');
		const semantic = other.waitForResponse(response => response.url().endsWith('/api/reviews'));
		await other.getByRole('button', { name: 'Sprawdź', exact: true }).click();
		expect((await semantic).status()).toBe(200);
		expect(await (await semantic).json()).toMatchObject({ source: 'ai', grade: 'again', progress: { version: 1 } });
		await expect(other.getByRole('heading', { name: 'Powtórz', exact: true })).toBeVisible();
		await other.getByRole('button', { name: 'RU -> PL', exact: true }).click();
		await expect(other.getByTestId('study-term')).toHaveText('Слово');
		await expect(other.getByText(WORD_DRAFT.examplePl, { exact: true })).toHaveCount(0);
		await other.getByLabel('Odpowiedź po polsku').fill('ошибка подключения');
		const failed = other.waitForResponse(response => response.url().endsWith('/api/reviews'));
		await other.getByRole('button', { name: 'Sprawdź', exact: true }).click();
		expect((await failed).status()).toBe(503);
		await expect(other.getByRole('alert')).toContainText('Model AI nie jest skonfigurowany. Poproś właściciela o sprawdzenie klucza API.');
		await expect(other.getByLabel('Odpowiedź po polsku')).toHaveValue('ошибка подключения');
		await expect(other.getByLabel('Odpowiedź po polsku')).toBeEnabled();
		await expect(other.getByRole('button', { name: 'Wyloguj', exact: true })).toBeVisible();
		await page.getByRole('button', { name: 'Nauka', exact: true }).click();
		await page.getByRole('button', { name: 'RU -> PL', exact: true }).click();
		await expect(page.getByTestId('study-term')).toHaveText('Слово');
		await expect(page.getByText(WORD_DRAFT.examplePl, { exact: true })).toHaveCount(0);
		let original = '';
		let resultA: ReviewResult | undefined;
		await page.route('**/api/reviews', async route => {
			original = route.request().postData()!;
			const response = await route.fetch();
			expect(response.status()).toBe(200);
			resultA = await response.json();
			await route.abort();
		});
		await page.getByLabel('Odpowiedź po polsku').fill('Słowo');
		await page.getByRole('button', { name: 'Sprawdź', exact: true }).click();
		await expect(page.getByRole('alert')).toContainText('Zapis odpowiedzi nie został potwierdzony');
		await page.unroute('**/api/reviews');
		await page.reload();
		await expect(page.getByLabel('Odpowiedź po polsku')).toHaveValue('Słowo');
		const retry = page.waitForResponse(response => response.url().endsWith('/api/reviews'));
		await page.getByRole('button', { name: 'Ponów', exact: true }).click();
		expect((await retry).request().postData()).toBe(original);
		expect(await (await retry).json()).toEqual(resultA);
		expect(resultA).toMatchObject({ source: 'exact', grade: 'correct', direction: 'ru-pl', progress: { version: 1 } });
		await expect(page.getByRole('heading', { name: 'Dobrze', exact: true })).toBeVisible();
		await expect(page.getByText(WORD_DRAFT.exampleRu, { exact: true })).toBeVisible();
		await expect(page.getByText(WORD_DRAFT.examplePl, { exact: true })).toBeVisible();
		const batchB: StudyBatch = await (await other.request.get('/api/study?direction=ru-pl')).json();
		const reverseBatchA: StudyBatch = await (await page.request.get('/api/study?direction=pl-ru')).json();
		expect(batchB.cards.find(item => item.card.id === cardId)?.progress).toBeNull();
		expect(reverseBatchA.cards.find(item => item.card.id === cardId)?.progress).toBeNull();
		await page.getByRole('button', { name: 'PL -> RU', exact: true }).click();
		await expect(page.getByTestId('study-term')).toHaveText('Słowo');
		await expect(page.getByText(WORD_DRAFT.exampleRu, { exact: true })).toHaveCount(0);
		await page.getByRole('button', { name: 'Pokaż odpowiedź', exact: true }).click();
		await expect(page.getByRole('heading', { name: 'Powtórz', exact: true })).toBeVisible();
		await expect(page.getByText(WORD_DRAFT.exampleRu, { exact: true })).toBeVisible();
		await expect(page.getByText(WORD_DRAFT.examplePl, { exact: true })).toBeVisible();
		await page.getByRole('button', { name: 'Słówka', exact: true }).click();
		await page.getByRole('button', { name: 'Słowo / Слово', exact: true }).click();
		await page.getByRole('button', { name: 'Do archiwum', exact: true }).click();
		await expect(page.getByRole('button', { name: 'Słowo / Слово', exact: true })).toHaveCount(0);
		const afterArchiveA: StudyBatch = await (await page.request.get('/api/study?direction=ru-pl')).json();
		const afterArchiveB: StudyBatch = await (await other.request.get('/api/study?direction=ru-pl')).json();
		expect(afterArchiveA.cards.some(item => item.card.id === cardId)).toBe(false);
		expect(afterArchiveB.cards.some(item => item.card.id === cardId)).toBe(false);
		await other.getByRole('button', { name: 'Ponów', exact: true }).click();
		await expect(other.getByTestId('study-term')).toHaveCount(0);
		await expect(other.getByLabel('Zapisana odpowiedź')).toHaveValue('ошибка подключения');
		await page.getByRole('button', { name: 'Nauka', exact: true }).click();
		await expect(page.getByTestId('study-term')).toHaveCount(0);
	} finally {
		const list = await allCards(page.request);
		const active = list.find(item => item.id === card?.id);
		if (active) expect((await page.request.patch(`/api/cards/${active.id}`, { headers, data: { version: active.version, archived: true } })).status()).toBe(200);
		await page.request.patch('/api/me', { headers, data: { direction: 'ru-pl' } });
		await other.request.patch('/api/me', { headers, data: { direction: 'ru-pl' } });
		await context.close();
	}
});
